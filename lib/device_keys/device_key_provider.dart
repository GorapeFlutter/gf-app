import 'dart:typed_data';

/// Local capabilities of an OS key provider.
class DeviceKeyAvailability {
  const DeviceKeyAvailability({
    required this.supported,
    required this.hardwareBacked,
    required this.attestationSupported,
    this.securityLevel,
    this.reason,
  });

  const DeviceKeyAvailability.unsupported(this.reason)
    : supported = false,
      hardwareBacked = false,
      attestationSupported = false,
      securityLevel = null;

  final bool supported;
  final bool hardwareBacked;
  final bool attestationSupported;
  final String? securityLevel;
  final String? reason;
}

/// A key generated by the OS key store.
///
/// No private key leaves the platform key store. The public key and evidence
/// are submitted to Gorape for registration.
class GeneratedDeviceKey {
  const GeneratedDeviceKey({
    required this.keyIdentifier,
    required this.publicKeyPem,
    required this.algorithm,
    required this.evidence,
    this.securityLevel,
  });

  final String keyIdentifier;
  final String publicKeyPem;
  final String algorithm;
  final Map<String, dynamic> evidence;
  final String? securityLevel;
}

/// OS-specific hardware-backed key operations.
///
/// Implementations must:
/// - create the key inside the OS key store (never in Dart memory),
/// - bind the attestation challenge into the key generation request,
/// - sign the raw decoded challenge bytes,
/// - return signatures as unpadded Base64url.
abstract interface class DeviceKeyProvider {
  String get platform;

  Future<DeviceKeyAvailability> availability();

  Future<GeneratedDeviceKey> generateKey({
    required String keyIdentifier,
    required Uint8List attestationChallenge,
  });

  Future<String> sign({required String keyIdentifier, required Uint8List data});

  Future<bool> hasKey(String keyIdentifier);

  Future<void> deleteKey(String keyIdentifier);
}
